def _date(v, name, errors):
    try:
        return date.fromisoformat(str(v))
    except ValueError:
        errors.append(f"{name} must be a date (YYYY-MM-DD)")
        return None

def _nights(ci, co):
    return (co - ci).days

def create_booking(conn, data, today=None):
    today = today or date.today()
    errors = _req(data, ["room", "check_in", "check_out", "name", "email"])
    _email(data, errors)
    if data.get("room") and ROOMS and data["room"] not in ROOMS:
        errors.append("room is unknown")
    ci = _date(data.get("check_in"), "check_in", errors) if data.get("check_in") else None
    co = _date(data.get("check_out"), "check_out", errors) if data.get("check_out") else None
    if ci and ci < today:
        errors.append("check_in cannot be in the past")
    if ci and co and co <= ci:
        errors.append("check_out must be after check_in")
    try:
        adults = int(data.get("adults", 1))
        children = int(data.get("children", 0) or 0)
        if not 1 <= adults <= 8 or not 0 <= children <= 8:
            errors.append("guest numbers out of range")
    except (TypeError, ValueError):
        errors.append("guest numbers must be integers")
        adults = children = 0
    if errors:
        raise ValidationError(errors)
    clash = conn.execute(
        "SELECT 1 FROM bookings WHERE room = ? AND status != 'cancelled' AND check_in < ? AND check_out > ?",
        (data["room"], co.isoformat(), ci.isoformat())).fetchone()
    if clash:
        raise Conflict("room is not available for those dates")
    # earning: calculate amount (nights * price, 10% deposit if payments disabled else full)
    nightly = ROOM_PRICES.get(data["room"], 12000) if isinstance(ROOM_PRICES, dict) else 12000
    nights = _nights(ci, co)
    amount = nightly * nights
    # store paid_amount for reference
    cur = conn.execute(
        "INSERT INTO bookings (room, check_in, check_out, adults, children, name, email, phone, requests, paid_amount_cents) VALUES (?,?,?,?,?,?,?,?,?,?)",
        (data["room"], ci.isoformat(), co.isoformat(), adults, children, data["name"].strip(),
         data["email"].strip(), data.get("phone"), data.get("requests"), amount))
    conn.commit()
    bid = cur.lastrowid
    # earning: if Stripe enabled for this site, create Checkout session for deposit/full amount
    checkout_url = None
    try:
        # decide amount: 20% deposit for demo, else full
        deposit = max(1500, amount // 5)  # min £15
        checkout_url = _stripe_checkout(deposit, f"Deposit for {data['room']} — {nights} night(s)", data.get("email"),
                                        success_url=os.getenv("BOOKING_SUCCESS_URL") or None,
                                        cancel_url=os.getenv("BOOKING_CANCEL_URL") or None)
        if checkout_url and "mock" not in checkout_url:
            conn.execute("UPDATE bookings SET stripe_session_id=? WHERE id=?", (checkout_url, bid))
            conn.commit()
        # attach mock flag else real url
    except Exception:
        pass
    return {"id": bid, "checkout_url": checkout_url, "amount_cents": amount}


def list_bookings(conn):
    return [dict(r) for r in conn.execute("SELECT * FROM bookings ORDER BY check_in")]

def booking_to_stripe_amount(room, check_in, check_out):
    try:
        ci = date.fromisoformat(check_in); co = date.fromisoformat(check_out)
        return ROOM_PRICES.get(room, 12000) * max(1, (co-ci).days)
    except Exception:
        return 12000
