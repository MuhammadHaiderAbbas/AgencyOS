def _stripe_checkout(amount_cents: int, description: str, customer_email: str | None, success_url: str | None, cancel_url: str | None):
    """Create Stripe Checkout session if STRIPE_SECRET_KEY set, else return mock URL."""
    key = os.getenv("STRIPE_SECRET_KEY") or os.getenv("STRIPE_SECRET_KEY_TEST")
    if not key:
        # mock earning – always works for demo, returns fake checkout that immediately succeeds
        return f"{success_url or '/'}#mock-checkout?amount={amount_cents}&desc={description[:20]}"
    try:
        import urllib.parse, urllib.request
        data = urllib.parse.urlencode({
            "mode": "payment",
            "success_url": success_url or "https://example.com/success?session_id={CHECKOUT_SESSION_ID}",
            "cancel_url": cancel_url or "https://example.com/cancel",
            "line_items[0][price_data][currency]": CURRENCY,
            "line_items[0][price_data][product_data][name]": description[:120],
            "line_items[0][price_data][unit_amount]": str(amount_cents),
            "line_items[0][quantity]": "1",
            "allow_promotion_codes": "true",
        }).encode()
        if customer_email:
            data += urllib.parse.urlencode({"customer_email": customer_email}).encode() and b"&customer_email="+urllib.parse.quote(customer_email).encode()
        req = urllib.request.Request("https://api.stripe.com/v1/checkout/sessions", data=data, headers={"Authorization": f"Bearer {key}"})
        with urllib.request.urlopen(req, timeout=15) as r:
            j = json.loads(r.read())
            return j.get("url")
    except Exception as e:
        # fall back to mock so site never blocks earning
        return f"{success_url or '/'}#mock-checkout-fallback"
