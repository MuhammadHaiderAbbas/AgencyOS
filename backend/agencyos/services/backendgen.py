SERVICE = r'''"""Business logic for the generated API. Pure functions over a sqlite3 connection."""
import re
import sqlite3
from datetime import date
from pathlib import Path

EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
ROOMS = __ROOMS__


class ValidationError(Exception):
    def __init__(self, errors):
        super().__init__("; ".join(errors))
        self.errors = errors


class Conflict(Exception):
    pass


def connect(path=":memory:"):
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.executescript((Path(__file__).parent / "schema.sql").read_text())
    return conn


def _req(data, fields):
    return [f"{f} is required" for f in fields if not str(data.get(f, "")).strip()]


def _email(data, errors):
    if data.get("email") and not EMAIL.match(str(data["email"])):
        errors.append("email is invalid")


def create_enquiry(conn, data):
    errors = _req(data, ["name", "email", "message"])
    _email(data, errors)
    if len(str(data.get("message", ""))) > 4000:
        errors.append("message is too long")
    if errors:
        raise ValidationError(errors)
    cur = conn.execute("INSERT INTO enquiries (name, email, message) VALUES (?, ?, ?)",
                       (data["name"].strip(), data["email"].strip(), data["message"].strip()))
    conn.commit()
    return cur.lastrowid
'''

SERVICE_BOOKING = r'''

def _date(v, name, errors):
    try:
        return date.fromisoformat(str(v))
    except ValueError:
        errors.append(f"{name} must be a date (YYYY-MM-DD)")
        return None


def create_booking(conn, data, today=None):
    today = today or date.today()
    errors = _req(data, ["room", "check_in", "check_out", "name", "email"])
    _email(data, errors)
    if data.get("room") and ROOMS and data["room"] not in ROOMS:
        errors.append("room is unknown")
    ci = _date(data.get("check_in"), "check_in", errors) if data.get("check_in") else None
    co = _date(data.get("check_out"), "check_out", errors) if data.get("check_out") else None
    if ci and ci < today:
        errors.append("check_in cannot be in the past")
    if ci and co and co <= ci:
        errors.append("check_out must be after check_in")
    try:
        adults = int(data.get("adults", 1))
        children = int(data.get("children", 0) or 0)
        if not 1 <= adults <= 8 or not 0 <= children <= 8:
            errors.append("guest numbers out of range")
    except (TypeError, ValueError):
        errors.append("guest numbers must be integers")
        adults = children = 0
    if errors:
        raise ValidationError(errors)
    clash = conn.execute(
        "SELECT 1 FROM bookings WHERE room = ? AND status != 'cancelled' AND check_in < ? AND check_out > ?",
        (data["room"], co.isoformat(), ci.isoformat())).fetchone()
    if clash:
        raise Conflict("room is not available for those dates")
    cur = conn.execute(
        "INSERT INTO bookings (room, check_in, check_out, adults, children, name, email, phone, requests) VALUES (?,?,?,?,?,?,?,?,?)",
        (data["room"], ci.isoformat(), co.isoformat(), adults, children, data["name"].strip(),
         data["email"].strip(), data.get("phone"), data.get("requests")))
    conn.commit()
    return cur.lastrowid


def list_bookings(conn):
    return [dict(r) for r in conn.execute("SELECT * FROM bookings ORDER BY check_in")]
'''

SERVICE_NEWS = r'''

def subscribe(conn, data):
    errors = _req(data, ["email"])
    _email(data, errors)
    if errors:
        raise ValidationError(errors)
    conn.execute("INSERT OR IGNORE INTO newsletter (email) VALUES (?)", (data["email"].strip().lower(),))
    conn.commit()
'''

SERVER = r'''"""Minimal JSON API server (stdlib only). Run: python server.py

Environment:
  DATABASE_PATH   sqlite file (default ./data.sqlite3)
  ADMIN_TOKEN     bearer token required for admin endpoints (no default — admin is disabled if unset)
  ALLOWED_ORIGIN  CORS origin of the website (default: same origin only)
  PORT            default 8080
"""
import hmac
import json
import os
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import service

DB = service.connect(os.getenv("DATABASE_PATH", "data.sqlite3"))
ADMIN_TOKEN = os.getenv("ADMIN_TOKEN")
ORIGIN = os.getenv("ALLOWED_ORIGIN", "")
MAX_BODY = 16_384

ROUTES = {
    "/api/enquiries": ("create_enquiry", "Thanks — we'll be in touch soon."),
    "/api/bookings": ("create_booking", "Thank you — your booking request has been received."),
    "/api/newsletter": ("subscribe", "You're subscribed."),
}


class Handler(BaseHTTPRequestHandler):
    def _send(self, code, body):
        raw = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("X-Content-Type-Options", "nosniff")
        if ORIGIN:
            self.send_header("Access-Control-Allow-Origin", ORIGIN)
            self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_OPTIONS(self):
        self._send(204, {})

    def do_GET(self):
        if self.path == "/api/health":
            return self._send(200, {"ok": True})
        if self.path == "/api/bookings" and hasattr(service, "list_bookings"):
            auth = self.headers.get("Authorization", "")
            if not ADMIN_TOKEN or not hmac.compare_digest(auth, f"Bearer {ADMIN_TOKEN}"):
                return self._send(401, {"error": "unauthorised"})
            return self._send(200, {"items": service.list_bookings(DB)})
        self._send(404, {"error": "not found"})

    def do_POST(self):
        route = ROUTES.get(self.path)
        if not route or not hasattr(service, route[0]):
            return self._send(404, {"error": "not found"})
        length = int(self.headers.get("Content-Length") or 0)
        if length > MAX_BODY:
            return self._send(413, {"error": "payload too large"})
        try:
            data = json.loads(self.rfile.read(length) or b"{}")
            if not isinstance(data, dict):
                raise ValueError
        except ValueError:
            return self._send(400, {"error": "invalid JSON"})
        try:
            getattr(service, route[0])(DB, data)
        except service.ValidationError as e:
            return self._send(422, {"error": "; ".join(e.errors), "errors": e.errors})
        except service.Conflict as e:
            return self._send(409, {"error": str(e)})
        self._send(201, {"message": route[1]})

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    port = int(os.getenv("PORT", "8080"))
    print(f"API listening on :{port}")
    ThreadingHTTPServer(("0.0.0.0", port), Handler).serve_forever()
'''

