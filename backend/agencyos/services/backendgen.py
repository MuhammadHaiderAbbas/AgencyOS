"""Backend generator used by the Database Engineer and Backend Developer agents.

Produces a dependency-free Python API (stdlib http.server + sqlite3) with real
validation logic and a unittest suite that the QA agent runs in the sandbox. The
OpenAPI spec is generated from the same entity model so spec and code stay aligned.
"""
from __future__ import annotations

from pathlib import Path


def entities(req: dict) -> list[str]:
    f = set(req.get("features") or [])
    ents = ["enquiries"]
    if "booking" in f:
        ents.insert(0, "bookings")
    if "newsletter" in f:
        ents.append("newsletter")
    if req.get("project_type") == "ecommerce":
        ents.append("orders")
    return ents


