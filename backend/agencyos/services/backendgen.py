def entities(req: dict) -> list[str]:
    f = set(req.get("features") or [])
    ents = ["enquiries"]
    if "booking" in f:
        ents.insert(0, "bookings")
    if "newsletter" in f:
        ents.append("newsletter")
    if req.get("project_type") == "ecommerce":
        ents.append("orders")
    # ecommerce always gets orders even without explicit flag for monetization
    if "payments" in f and "orders" not in ents:
        # enable orders for any payments site (donations, etc.)
        if req.get("project_type") != "ecommerce":
            pass  # bookings handles payments for hotel
    return ents


