TESTS_TAIL = "\n\nif __name__ == '__main__':\n    unittest.main()\n"


def write_backend(api_dir: Path, req: dict, room_ids: list[str]) -> list[str]:
    api_dir.mkdir(parents=True, exist_ok=True)
    (api_dir / "tests").mkdir(exist_ok=True)
    ents = entities(req)
    # nightly prices per room (earning): scale by name length heuristic for demo
    prices = {}
    for rid in room_ids:
        # base £95-£290 based on tier
        base = 9500
        if "suite" in rid: base = 18500
        if "penthouse" in rid or "presidential" in rid: base = 29000
        prices[rid] = base
    svc = SERVICE.replace("__ROOMS__", repr(room_ids)).replace("__ROOM_PRICES__", repr(prices))
    tests = TESTS
    if "bookings" in ents:
        svc += SERVICE_BOOKING
        tests += TESTS_BOOKING
    if "newsletter" in ents:
        svc += SERVICE_NEWS
    if "orders" in ents:
        svc += SERVICE_ORDERS
        tests += TESTS_ORDERS
    (api_dir / "service.py").write_text(svc)
    (api_dir / "server.py").write_text(SERVER)
    (api_dir / "tests" / "__init__.py").write_text("")
    (api_dir / "tests" / "test_service.py").write_text(tests + TESTS_TAIL)
    (api_dir / ".env.example").write_text(
        "DATABASE_PATH=data.sqlite3\nADMIN_TOKEN=change-me\nALLOWED_ORIGIN=https://your-site.example\nPORT=8080\n"
        "# Earning: set Stripe keys to take real payments (mock checkout works without them)\n"
        "STRIPE_SECRET_KEY=\nSTRIPE_PUBLISHABLE_KEY=\nBOOKING_SUCCESS_URL=https://your-site.example/success.html\nBOOKING_CANCEL_URL=https://your-site.example/cancel.html\n"
    )
    # generate extra earning readme
    (api_dir / "EARNING.md").write_text(
        "# Earning with this API\n"
        "Bookings: POST /api/bookings {room,check_in,check_out,adults,name,email} -> {id,checkout_url,amount_cents}\n"
        "Follow checkout_url to pay deposit via Stripe (mock URL if no STRIPE_SECRET_KEY).\n"
        "Orders: POST /api/orders/checkout {items:[{id,name,price}],email} -> {checkout_url}\n"
        "Admin: GET /api/bookings + GET /api/orders requires Authorization: Bearer $ADMIN_TOKEN\n"
        "Emails captured via newsletter build an owned audience.\n"
    )
    return ["source/api/service.py", "source/api/server.py", "source/api/tests/test_service.py", "source/api/.env.example", "source/api/EARNING.md"]
