ORDER_ROUTES = {
    "/api/orders/checkout": "create_order_checkout",
    "/api/orders": "create_order",
}


class Handler(BaseHTTPRequestHandler):
    def _send(self, code, body):
        raw = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Cache-Control", "no-store")
        if ORIGIN:
            self.send_header("Access-Control-Allow-Origin", ORIGIN)
            self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        else:
            self.send_header("Access-Control-Allow-Origin", "*")
            self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_OPTIONS(self):
        self._send(204, {})

    def do_GET(self):
        if self.path == "/api/health":
            return self._send(200, {"ok": True, "earning": bool(os.getenv("STRIPE_SECRET_KEY"))})
        if self.path.startswith("/api/bookings") and hasattr(service, "list_bookings"):
            if self.path == "/api/bookings" or self.path.startswith("/api/bookings?"):
                auth = self.headers.get("Authorization", "")
                if not ADMIN_TOKEN or not hmac.compare_digest(auth, f"Bearer {ADMIN_TOKEN}"):
                    return self._send(401, {"error": "unauthorised"})
                return self._send(200, {"items": service.list_bookings(DB)})
        if self.path.startswith("/api/orders") and hasattr(service, "list_orders"):
            auth = self.headers.get("Authorization", "")
            if not ADMIN_TOKEN or not hmac.compare_digest(auth, f"Bearer {ADMIN_TOKEN}"):
                return self._send(401, {"error": "unauthorised"})
            return self._send(200, {"items": service.list_orders(DB)})
        if self.path == "/api/config":
            # public config for frontend (no secrets)
            return self._send(200, {"stripePublishableKey": bool(os.getenv("STRIPE_PUBLISHABLE_KEY")), "currency": "gbp"})
        self._send(404, {"error": "not found"})

    def do_POST(self):
        # orders checkout
        if self.path == "/api/orders/checkout" and hasattr(service, "create_order_checkout"):
            length = int(self.headers.get("Content-Length") or 0)
            try:
                data = json.loads(self.rfile.read(length) or b"{}")
                res = service.create_order_checkout(DB, data)
                return self._send(200, {"ok": True, "checkout_url": res.get("checkout_url"), "id": res.get("id"), "total_cents": res.get("total_cents")})
            except service.ValidationError as e:
                return self._send(422, {"error": "; ".join(e.errors)})
            except Exception as e:
                return self._send(500, {"error": str(e)[:300]})
        if self.path == "/api/orders" and hasattr(service, "create_order"):
            length = int(self.headers.get("Content-Length") or 0)
            try:
                data = json.loads(self.rfile.read(length) or b"{}")
                res = service.create_order(DB, data)
                return self._send(201, {"ok": True, "id": res["id"]})
            except service.ValidationError as e:
                return self._send(422, {"error": "; ".join(e.errors)})
        route = ROUTES.get(self.path)
        if not route or not hasattr(service, route[0]):
            return self._send(404, {"error": "not found"})
        length = int(self.headers.get("Content-Length") or 0)
        if length > MAX_BODY:
            return self._send(413, {"error": "payload too large"})
        try:
            data = json.loads(self.rfile.read(length) or b"{}")
            if not isinstance(data, dict):
                raise ValueError
        except ValueError:
            return self._send(400, {"error": "invalid JSON"})
        try:
            res = getattr(service, route[0])(DB, data)
            # booking may return dict with checkout_url for earning
            if isinstance(res, dict) and res.get("checkout_url"):
                return self._send(201, {"message": route[1], "id": res.get("id"), "checkout_url": res.get("checkout_url"), "amount_cents": res.get("amount_cents")})
            return self._send(201, {"message": route[1], "id": res if isinstance(res, int) else res.get("id") if isinstance(res, dict) else None})
        except service.ValidationError as e:
            return self._send(422, {"error": "; ".join(e.errors), "errors": e.errors})
        except service.Conflict as e:
            return self._send(409, {"error": str(e)})

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    port = int(os.getenv("PORT", "8080"))
    print(f"API listening on :{port}  earning={'ON' if os.getenv('STRIPE_SECRET_KEY') else 'mock (demo checkout)'}")
    ThreadingHTTPServer(("0.0.0.0", port), Handler).serve_forever()
